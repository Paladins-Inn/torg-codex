package de.paladinsinn.drivethru.resource;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Single-resource JSON:API document ({@code data} plus optional sideloaded {@code included} items).
 *
 * @param <A> primary resource attributes type
 */
@JsonIgnoreProperties(ignoreUnknown = true)
@NoArgsConstructor
@Getter
@Setter
@ToString(onlyExplicitlyIncluded = true)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class JsonApiDocument<A> {

    @ToString.Include
    @EqualsAndHashCode.Include
    private JsonApiResource<A> data;

    private List<JsonApiResource<Map<String, Object>>> included;

    @JsonIgnore
    public Optional<A> getAttributes() {
        return Optional.ofNullable(data).map(JsonApiResource::getAttributes);
    }
}
